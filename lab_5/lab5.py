def get_edge_weight(station1, station2):
    """
    Определяет вес ребра между двумя станциями.
    Если станции на одной линии — вес линии.
    Если это переход — 1 минута.
    """
    lines1 = set(STATION_LINES.get(station1, []))
    lines2 = set(STATION_LINES.get(station2, []))

    # Если есть общая линия — это движение по линии
    common_lines = lines1 & lines2
    if common_lines:
        # Берём минимальный вес из общих линий
        return min(LINE_WEIGHTS[line] for line in common_lines)

    # Если нет общей линии — это переход
    return LINE_WEIGHTS["transfer"]


def dijkstra(graph, start, goal):
    """
    Алгоритм Дейкстры для поиска кратчайшего пути по времени.
    """
    # Приоритетная очередь: (время, станция, путь)
    queue = [(0, start, [start])]
    visited = set()

    while queue:
        time, current, path = heapq.heappop(queue)

        if current == goal:
            return path, time

        if current in visited:
            continue

        visited.add(current)

        for neighbor in graph.get(current, []):
            if neighbor not in visited:
                weight = get_edge_weight(current, neighbor)
                new_time = time + weight
                new_path = path + [neighbor]
                heapq.heappush(queue, (new_time, neighbor, new_path))

    return None, float('inf')


def print_route(path, total_time, algorithm_name="Дейкстра"):
    """Выводит маршрут в читаемом формате."""
    if path is None:
        print(f"[{algorithm_name}] Маршрут не найден")
    else:
        print(f"[{algorithm_name}] {' -> '.join(path)}")
        print(f"[{algorithm_name}] Общее время: {total_time} минут")
        print(f"[{algorithm_name}] Количество станций: {len(path)}")


