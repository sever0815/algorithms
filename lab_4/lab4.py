def bfs(graph, start, goal):
    """
    Поиск в ширину (BFS).
    Находит кратчайший путь (по количеству рёбер).
    """
    if start == goal:
        return [start]

    queue = deque([[start]])
    visited = {start}

    while queue:
        path = queue.popleft()
        node = path[-1]

        for neighbor in graph.get(node, []):
            if neighbor not in visited:
                new_path = path + [neighbor]
                if neighbor == goal:
                    return new_path
                visited.add(neighbor)
                queue.append(new_path)

    return None


def dfs(graph, start, goal):
    """
    Поиск в глубину (DFS).
    Находит какой-либо путь (не обязательно кратчайший).
    """
    if start == goal:
        return [start]

    stack = [[start]]
    visited = {start}

    while stack:
        path = stack.pop()
        node = path[-1]

        for neighbor in graph.get(node, []):
            if neighbor not in visited:
                new_path = path + [neighbor]
                if neighbor == goal:
                    return new_path
                visited.add(neighbor)
                stack.append(new_path)

    return None


def print_path(path, algorithm_name):
    """Выводит путь в читаемом формате."""
    if path is None:
        print(f"[{algorithm_name}] Путь не найден")
    else:
        print(f"[{algorithm_name}] {' -> '.join(path)}")
        print(f"[{algorithm_name}] Количество станций: {len(path)}")


